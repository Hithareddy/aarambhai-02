PACK: dict[str, list[Item]] = {
    "early_learner": EARLY_LEARNER,
    "school_student": SCHOOL_STUDENT,
    "homemaker": HOMEMAKER,
    "senior_citizen": SENIOR_CITIZEN,
    "college_student": COLLEGE_STUDENT,
    "professional": PROFESSIONAL,
}

# Personas that may also share another persona's items (close real-life worlds).
SHARED_WITH: dict[str, tuple[str, ...]] = {
    "early_learner": ("early_learner",),
    "school_student": ("school_student", "early_learner"),
    "college_student": ("college_student", "professional"),
    "professional": ("professional", "college_student"),
    "homemaker": ("homemaker", "senior_citizen", "general_adult"),
    "senior_citizen": ("senior_citizen", "homemaker", "general_adult"),
}


def iter_items() -> list[dict[str, Any]]:
    """Flatten the pack into seedable dicts with stable ids and persona tags."""
    rows: list[dict[str, Any]] = []
    for persona, items in PACK.items():
        prefix = "".join(part[0] for part in persona.split("_")).upper()
        for idx, (skill, difficulty, qtype, context, instruction, prompt,
                  options, answer, audio) in enumerate(items, start=1):
            personas = sorted({p for p, shared in SHARED_WITH.items() if persona in shared} | {persona})
            rows.append({
                "id": f"PP-{prefix}-{idx:03d}",
                "persona": persona,
                "personas": personas,
                "skill": skill,
                "difficulty": difficulty,
                "question_type": qtype,
                "context": context,
                "instruction": instruction,
                "prompt": prompt,
                "options": options,
                "correct_answer": answer,
                "audio_script": audio,
            })
    return rows
